-- Daily View dashboard: recurring-event series foundation (birthday/anniversary reminders).
-- Adds `dv_event_series` per the build spec's section 6.2 (RFC 5545 rrule design), `series_id`
-- on `dv_event`, a `birthday` event type and `recurring_series` event source, and a
-- yearly-only occurrence generator + trigger. Weekly/daily/monthly rrule values are accepted by
-- the schema for forward-compatibility but are not yet generated -- see
-- dv_generate_series_occurrences() below.
--
-- Verified against the live schema before writing this file: dv_event_type currently seeds
-- appointment/meal/medication/other/reminder/routine/task/visit (no 'birthday');
-- dv_event_source seeds calendar_sync/manual/mobile_message/system_generated/web_dashboard (no
-- 'recurring_series'); dv_event_status seeds cancelled/completed/missed/scheduled;
-- dv_event_visibility seeds display/private/supporters_only. All differ from the informal spec
-- doc's seed lists, per the existing caution in 20260706112913_dv_today_page.sql.
--
-- Scope note: this project also hosts an unrelated schema (block/cube/cuboid/...) for a
-- separate app. Nothing here touches any table outside the dv_ prefix.

-- ============================================================================
-- 1. dv_event_series
-- ============================================================================

create table if not exists public.dv_event_series (
  series_id             bigint generated by default as identity primary key,
  account_id            bigint not null references public.dv_account(account_id),
  title                 text not null,
  description           text null,
  start_date            date not null,
  end_date              date null,
  start_time            time null,
  end_time              time null,
  rrule                 text not null,
  event_type_id         bigint null references public.dv_event_type(event_type_id),
  event_visibility_id   bigint not null references public.dv_event_visibility(event_visibility_id),
  event_source_id       bigint null references public.dv_event_source(event_source_id),
  event_accuracy_id     bigint null references public.dv_event_accuracy(event_accuracy_id),
  display_priority      smallint not null default 5,
  show_on_display       boolean not null default true,
  is_active             boolean not null default true,
  created_by_user_id    bigint null references public.dv_user(user_id),
  updated_by_user_id    bigint null references public.dv_user(user_id),
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),
  deleted_at            timestamptz null
);

create index if not exists dv_event_series_account_idx
  on public.dv_event_series (account_id)
  where deleted_at is null;

alter table public.dv_event_series enable row level security;

