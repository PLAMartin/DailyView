alter table public.dv_event
  add column if not exists series_id bigint null references public.dv_event_series(series_id);

-- Marks an occurrence as edited independently of its series ("this occurrence only" in the
-- dashboard's edit dialog). dv_sync_series_occurrences() below skips overridden rows when a
-- series-level edit ("entire series") pushes new field values out to future occurrences -- this
-- is what implements the spec's "editing the series updates future, non-overridden occurrences
-- only" rule. The dashboard is responsible for setting this to true on an occurrence-only edit;
-- it is never set by the series-sync path itself.
alter table public.dv_event
  add column if not exists series_overridden boolean not null default false;

create index if not exists dv_event_series_id_idx
  on public.dv_event (series_id)
  where series_id is not null and deleted_at is null;

